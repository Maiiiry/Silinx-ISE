export const SYMBOLS = Object.keys(GLYPHS).sort((a, b) => order(a) - order(b) || (a < b ? -1 : 1));
function order(c) { return /[A-Z]/.test(c) ? 0 : /[a-z]/.test(c) ? 1 : /[0-9]/.test(c) ? 2 : 3; }

/** The width of a glyph (its widest variant) plus the space after it, in cap heights. */
export function advance(ch) {
  const vs = GLYPHS[ch];
  if (!vs) return 0.6;
  const w = Math.max(...vs.map(v => Math.max(...v.flat().map(p => p[0]))));
  return w + 0.25;
}
