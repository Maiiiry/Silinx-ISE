// Silinx ink - the skeleton font (#1056): every symbol of the handwritten expressions as the strokes a pen draws,
// in variants (one storey or two, with or without a bar...). The built-in templates are made from it
// (scripts/ink-templates.mjs -> core/ink/templates.json), and the tests write expressions with it (core/ink/synth.js).
//
// Units: the cap height is 1 (y = 0 at the top of a capital, y = 1 on the baseline, y grows downwards), the
// x-height is 0.55 (lower-case letters from y = 0.45), descenders reach y = 1.35. x starts at 0 for each glyph.
//
//   GLYPHS: { ch: [variant, ...] }, a variant: [stroke, ...], a stroke: [[x, y], ...]
//   SYMBOLS: the symbols of the set, in order; advance(ch): the glyph's width plus its spacing

const STEP = 10;   // degrees between the points of an arc

// a polyline: L(x0, y0, x1, y1, ...)
const L = (...c) => { const p = []; for (let i = 0; i < c.length; i += 2) p.push([c[i], c[i + 1]]); return p; };
// an arc of an ellipse from angle a0 to a1 (degrees; 0 = right, 90 = down: a1 > a0 turns clockwise on the screen)
function A(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / STEP));
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });
}
// one stroke from pieces drawn one after the other
const S = (...pieces) => pieces.flat();
const dot = (x, y, r = 0.035) => A(x, y, r, r, 0, 360);

// lower-case bowls (x-height 0.45..1)
const bowl = (cx = 0.25, a0 = -90, a1 = 270) => A(cx, 0.725, 0.25, 0.275, a0, a1);

