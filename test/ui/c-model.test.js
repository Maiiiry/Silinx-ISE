// UI (#1530): an HDL module's C model: its process View C Model (both views) opens the model, read-only (its struct, its
// _init / _eval / _step); a design that cannot be modelled said in the Console; Portuguese; both interfaces. No warnings.
import { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { setupUi, uiTest, makeProject } from './harness.js';

let env;
before(async () => { env = await setupUi(); });
after(async () => { await env?.teardown?.(); });
const E = () => env;

const CNT = `library ieee; use ieee.std_logic_1164.all; use ieee.numeric_std.all;
entity counter is port (clk, rst, en: in std_logic; q: out unsigned(3 downto 0)); end;
architecture rtl of counter is
  signal c: unsigned(3 downto 0) := (others => '0');
begin
  process (clk) begin
    if rising_edge(clk) then
      if rst = '1' then c <= (others => '0'); elsif en = '1' then c <= c + 1; end if;
    end if;
  end process;
  q <= c;
end;
`;
const NEG = 'module neg(input clk, input d, output reg q);\n  always @(negedge clk) q <= d;\nendmodule\n';

uiTest('#1530 View C Model: an HDL module\'s C model, read-only (its _step); a design that cannot be one said; Portuguese', E, async (page) => {
  await makeProject(env, { name: 'CModel', top: 'counter', files: { 'src/counter.vhd': CNT, 'src/neg.v': NEG } });
  await page.openProject('CModel');
  await page.showMessages();
  await page.treeRow('#hier', 'counter');
  await page.treeRow('#procs', 'View C Model', { dbl: true, exact: true });
  await page.waitFor(() => window.Silinx.active?.id === 'cmodel:counter' && window.Silinx.active.editor, [], { what: 'the C model' });
  const doc = await page.eval(() => ({ ro: window.Silinx.active.editor.view.state.readOnly, text: window.Silinx.active.editor.getValue(), banner: document.querySelector('.doc:not([hidden]) .gen-banner')?.textContent, title: window.Silinx.active.title }));
  assert.equal(doc.ro, true);
  assert.equal(doc.title, 'counter_model.c');
  assert.equal(doc.banner, 'Read-only, the C model of counter');
  assert.match(doc.text, /^\/\* Generated by Silinx: a C model of 'counter'/);
  assert.match(doc.text, /^typedef struct \{\n {2}uint8_t clk;/m);
  assert.match(doc.text, /^void counter_step\(counter_t \*s\) \{$/m);
  assert.match(await page.consoleText(), /The C model of 'counter': sequential, counter_step a rising edge of clk\./);
  // the Simulation view has it too; a design that cannot be modelled: said
  await page.setView('sim');
  await page.treeRow('#hier', 'neg');
  await page.treeRow('#procs', 'View C Model', { dbl: true, exact: true });
  await page.waitConsole(/ERROR: the C model of 'neg': a falling edge of 'clk': only rising edges are modelled \(line 2, src\/neg\.v\)/);
  await page.setView('impl');
  // in Portuguese
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('pt'));
  await page.treeRow('#hier', 'counter');
  await page.treeRow('#procs', 'Ver Modelo C', { dbl: true, exact: true });
  await page.waitFor(() => window.Silinx.active?.id === 'cmodel:counter' && document.querySelector('.doc:not([hidden]) .gen-banner')?.textContent === 'Só de leitura, o modelo C de counter', [], { what: 'Portuguese' });
  await page.eval(async () => (await import('/js/i18n.js')).setLanguage('en'));
  assert.deepEqual(page.console.filter((c) => c.type === 'warning' || c.type === 'warn').map((c) => c.text), []);
});
